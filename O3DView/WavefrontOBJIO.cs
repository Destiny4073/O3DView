public static class WavefrontOBJIO
{
    public static void WriteOBJ(O3DFile mesh, string path, string name)
    {
        try
        {
            using var writer = new StreamWriter(path);
            WriteHeader(name, writer);

            string mtlPath = Path.ChangeExtension(path, ".mtl");
            writer.WriteLine($"mtllib {Path.GetFileName(mtlPath)}");
            writer.WriteLine($"s 0");
            writer.WriteLine();

            foreach (var vert in mesh.vertices)
                writer.WriteLine($"v {-vert.pos.x} {vert.pos.y} {vert.pos.z}");

            writer.WriteLine();
            foreach (var vert in mesh.vertices)
                writer.WriteLine($"vt {vert.uv.x} {1 - vert.uv.y}");

            writer.WriteLine();
            foreach (var vert in mesh.vertices)
                writer.WriteLine($"vn {-vert.normal.x} {vert.normal.y} {vert.normal.z}");

            int lastMatl = -1;
            foreach (var tri in mesh.triangles)
            {
                if (tri.mat != lastMatl)
                {
                    writer.WriteLine($"g matl_{tri.mat}");
                    writer.WriteLine($"usemtl matl_{tri.mat}");
                    lastMatl = tri.mat;
                }
                writer.WriteLine($"f {tri.c + 1}/{tri.c + 1}/{tri.c + 1} {tri.b + 1}/{tri.b + 1}/{tri.b + 1} {tri.a + 1}/{tri.a + 1}/{tri.a + 1}");
            }

            WriteMTL(in mesh, mtlPath, name);
        }
        catch (Exception ex)
        {
            Program.Log($"Couldn't write obj file: {ex}", "OBJ IO", GUI.GUIController.Severity.Error);
        }
    }

    private static void WriteHeader(string name, StreamWriter writer)
    {
        var version = Application.ProductVersion;
#if DEBUG
        string build = "Debug";
#else
            string build = "Release";
#endif
        writer.WriteLine($"""
                ###########################################################
                # Generated by O3D-View version {version}-{build}
                # {name}
                ###########################################################

                """);
    }

    private static void WriteMTL(in O3DFile mesh, string path, string name)
    {
        try
        {
            using var writer = new StreamWriter(path);

            WriteHeader(name, writer);

            int i = 0;
            foreach (var mat in mesh.materials)
            {
                writer.WriteLine($"newmtl matl_{i}");
                writer.WriteLine($"Ka {mat.diffuse.x} {mat.diffuse.y} {mat.diffuse.z}");
                writer.WriteLine($"Kd {mat.diffuse.x} {mat.diffuse.y} {mat.diffuse.z}");
                writer.WriteLine($"Ks {mat.spec.x} {mat.spec.y} {mat.spec.z}");
                writer.WriteLine($"Ns {Math.Clamp(mat.specPower, 0, 1000)}");
                writer.WriteLine($"Ke {mat.emission.x} {mat.emission.y} {mat.emission.z}");
                writer.WriteLine($"d {mat.diffuse.w}");
                if (mat.diffuse.w != 1)
                    writer.WriteLine($"Tr {1 - mat.diffuse.w}");
                writer.WriteLine($"illum 2");
                if (!string.IsNullOrEmpty(mat.textureName))
                    writer.WriteLine($"map_Kd texture/{mat.textureName}");
                writer.WriteLine();

                i++;
            }
        }
        catch (Exception ex)
        {
            Program.Log($"Couldn't write mtl file: {ex}", "OBJ IO", GUI.GUIController.Severity.Error);
        }
    }

    public static O3DFile ReadOBJ(string path)
    {
        using StreamReader reader = new(path);

        List<O3DVec3> positions = [];
        List<O3DVec2> uvs = [];
        List<O3DVec3> normals = [];
        List<O3DTri> triangles = [];
        List<O3DVert> verts = [];
        Dictionary<(int p, int uv, int n), int> vertsDict = [];
        Dictionary<string, int> mtlsDict = [];
        List<O3DMaterial> materials = [];

        string? line;
        Span<Range> splitsBuff = stackalloc Range[8];
        Span<Range> faceSplitsBuff = stackalloc Range[4];
        int lineNo = 0;
        Span<int> tempTri = stackalloc int[4];
        ushort currentMat = 0;
        while ((line = reader.ReadLine()) != null)
        {
            ReadOnlySpan<char> l = line.AsSpan().Trim();
            lineNo++;

            if (l.Length > 0 && l[0] == '#')
                continue;

            int nSplits = l.Split(splitsBuff, ' ', StringSplitOptions.RemoveEmptyEntries);
            var splits = splitsBuff[..nSplits];

            if (splits.Length == 0)
                continue;

            switch (l[splits[0]])
            {
                case "v":
                    if (splits.Length < 4)
                        throw new FormatException($"Malformed OBJ file on line {lineNo}. Vertex position must specify at least three components.");
                    positions.Add(new(
                        -float.Parse(l[splits[1]]),
                        float.Parse(l[splits[2]]),
                        float.Parse(l[splits[3]])
                        ));
                    break;
                case "vn":
                    if (splits.Length != 4)
                        throw new FormatException($"Malformed OBJ file on line {lineNo}. Vertex normal must specify three components.");
                    normals.Add(new(
                        -float.Parse(l[splits[1]]),
                        float.Parse(l[splits[2]]),
                        float.Parse(l[splits[3]])
                        ));
                    break;
                case "vt":
                    if (splits.Length < 3)
                        throw new FormatException($"Malformed OBJ file on line {lineNo}. Vertex texcoord must specify at least two components.");
                    uvs.Add(new(
                        float.Parse(l[splits[1]]),
                        1-float.Parse(l[splits[2]])
                        ));
                    break;
                case "f":
                    if (splits.Length != 4 && splits.Length != 5)
                        throw new FormatException($"Malformed OBJ file on line {lineNo}. Only triangle/quad faces are supported.");

                    // Faces are defined in the form:
                    // f v/vt/vn v/vt/vn v/vt/vn
                    // Optionally the last vt or the vn can be omitted: f v//vn ... or f v/vt ...
                    // We need to find all the unique combinations of v/vt/vn in the faces to make separate O3DVerts for each of them
                    for (int i = 0; i < splits.Length - 1; i++)
                    {
                        var part = l[splits[i + 1]];
                        int nFaceSplits = part.Split(faceSplitsBuff, '/');
                        var faceSplits = faceSplitsBuff[..nFaceSplits];
                        // Should never happen
                        if (faceSplits.Length < 1)
                            throw new FormatException($"Malformed OBJ file on line {lineNo}. Face must specify a vertex position.");
                        int pos = int.Parse(part[faceSplits[0]]);
                        int vt = -1;
                        int vn = -1;
                        if (faceSplits.Length >= 2)
                        {
                            var vtSpan = part[faceSplits[1]];
                            if (!vtSpan.IsEmpty)
                                vt = int.Parse(vtSpan);
                        }
                        if (faceSplits.Length >= 3)
                        {
                            var vnSpan = part[faceSplits[2]];
                            if (!vnSpan.IsEmpty)
                                vn = int.Parse(vnSpan);
                        }

                        if (!vertsDict.TryGetValue((pos, vt, vn), out var vert))
                        {
                            // This vertex is some unique combination of position, normal, and uv, add it to the dictionary
                            vert = verts.Count;
                            vertsDict.Add((pos, vt, vn), vert);
                            var p = pos >= 1 && pos <= positions.Count ? positions[pos - 1] : throw new FormatException($"Malformed OBJ file on line {lineNo}. Face specifies an invalid vertex position {pos}.");
                            var n = vn >= 1 && vn <= normals.Count ? normals[vn - 1] : default;
                            var t = vt >= 1 && vt <= uvs.Count ? uvs[vt - 1] : default;
                            verts.Add(new(p, n, t));
                        }
                        tempTri[i] = vert;
                    }
                    triangles.Add(new((uint)tempTri[2], (uint)tempTri[1], (uint)tempTri[0], currentMat));
                    if (splits.Length == 5)
                    {
                        // Convert quad to tris
                        // 0---3---5
                        // | \ | \ |
                        // 1---2---4
                        triangles.Add(new((uint)tempTri[3], (uint)tempTri[2], (uint)tempTri[0], currentMat));
                    }
                    break;
                case "o":
                    break;
                case "s":
                    break;
                case "g":
                    break;
                case "mtllib":
                    string mtlPath = new(l[splits[1].Start..]);
                    mtlPath = mtlPath.Replace('/', Path.DirectorySeparatorChar);
                    mtlPath = Path.Combine(Path.GetDirectoryName(path) ?? string.Empty, mtlPath);
                    ReadMTL(mtlPath, mtlsDict, materials);
                    break;
                case "usemtl":
                    string mtlKey = new(l[splits[1].Start..]);
                    if (!mtlsDict.TryGetValue(mtlKey, out var mat))
                        Program.Log($"Malformed OBJ file on line {lineNo}. No material named '{mtlKey}' found in mtl file.", "O3DIO", GUI.GUIController.Severity.Warning);
                    //    throw new FormatException($"Malformed OBJ file on line {lineNo}. No material named '{mtlKey}' found in mtl file.");
                    currentMat = (ushort)mat;
                    break;
            }
        }

        if (materials.Count == 0)
        {
            // Create a default material is none were loaded.
            materials.Add(new(O3DVec4.One, O3DVec3.Zero, O3DVec3.Zero, 8, string.Empty));
        }

        return new O3DFile()
        {
            encryptionKey = 0xffffffff,
            extendedOptions = O3DExtendedOptions.LONG_TRIANGLE_INDICES,
            version = 7,
            vertices = verts.ToArray(),
            triangles = triangles.ToArray(),
            materials = materials.ToArray(),
            transform = Matrix4x4.Identity
        };
    }

    public static void ReadMTL(string path, Dictionary<string, int> mtlsDict, List<O3DMaterial> mtls)
    {
        try
        {
            using StreamReader reader = new(path);

            O3DMaterial defaultMat = new(O3DVec4.One, O3DVec3.Zero, O3DVec3.Zero, 8, string.Empty);
            O3DMaterial current = defaultMat;
            bool shouldAdd = false;

            string dirName = Path.GetDirectoryName(path) ?? string.Empty;
            string? line;
            Span<Range> splitsBuff = stackalloc Range[8];
            int lineNo = 0;
            while ((line = reader.ReadLine()) != null)
            {
                ReadOnlySpan<char> l = line.AsSpan().Trim();
                lineNo++;

                if (l.Length > 0 && l[0] == '#')
                    continue;

                int nSplits = l.Split(splitsBuff, ' ', StringSplitOptions.RemoveEmptyEntries);
                var splits = splitsBuff[..nSplits];

                if (splits.Length == 0)
                    continue;

                switch (l[splits[0]])
                {
                    case "newmtl":
                        if (shouldAdd)
                            mtls.Add(current);
                        shouldAdd = true;
                        current = defaultMat;
                        if (splits.Length <= 1)
                            throw new FormatException($"Malformed MTL file on line {lineNo}. Material definition must be followed by a material name.");
                        if (!mtlsDict.TryAdd(new(l[splits[1].Start..]), mtls.Count))
                            throw new FormatException($"Malformed MTL file on line {lineNo}. Material name must be unique within the material library.");
                        break;
                    case "Ke":
                        if (splits.Length != 4)
                            throw new FormatException($"Malformed MTL file on line {lineNo}. Emissive colour must specify three components.");
                        current.emission = new(
                            float.Parse(l[splits[1]]),
                            float.Parse(l[splits[2]]),
                            float.Parse(l[splits[3]]));
                        break;
                    case "Kd":
                        if (splits.Length != 4)
                            throw new FormatException($"Malformed MTL file on line {lineNo}. Diffuse colour must specify three components.");
                        current.diffuse = new(
                            float.Parse(l[splits[1]]),
                            float.Parse(l[splits[2]]),
                            float.Parse(l[splits[3]]),
                            current.diffuse.w);
                        break;
                    case "Ks":
                        if (splits.Length != 4)
                            throw new FormatException($"Malformed MTL file on line {lineNo}. Specular colour must specify three components.");
                        current.spec = new(
                            float.Parse(l[splits[1]]),
                            float.Parse(l[splits[2]]),
                            float.Parse(l[splits[3]]));
                        break;
                    case "Ns":
                        if (splits.Length != 2)
                            throw new FormatException($"Malformed MTL file on line {lineNo}. Specular power must specify one component.");
                        current.specPower = float.Parse(l[splits[1]]);
                        break;
                    case "d":
                        if (splits.Length != 2)
                            throw new FormatException($"Malformed MTL file on line {lineNo}. Alpha must specify one component.");
                        current.diffuse.w = float.Parse(l[splits[1]]);
                        break;
                    case "Tr":
                        if (splits.Length != 2)
                            throw new FormatException($"Malformed MTL file on line {lineNo}. Alpha must specify one component.");
                        current.diffuse.w = 1 - float.Parse(l[splits[1]]);
                        break;
                    case "map_Kd":
                        if (splits.Length < 2)
                            throw new FormatException($"Malformed MTL file on line {lineNo}. Texture must specify a valid file.");
                        string texPath = new(l[splits[1].Start..]);
                        /*texPath = texPath.Replace('/', Path.DirectorySeparatorChar);
                        texPath = Path.Combine(dirName, texPath);*/
                        current.textureName = texPath;
                        break;
                }
            }
            if (shouldAdd)
                mtls.Add(current);
        }
        catch (Exception ex)
        {
            Program.Log($"Couldn't read mtl file: {ex}", "OBJ IO", GUI.GUIController.Severity.Error);
        }
    }
}
